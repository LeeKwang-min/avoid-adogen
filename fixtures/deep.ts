// @ts-nocheck
// 티어 3단계를 한 화면에서 확인하는 픽스처.
// 실제로 동작하는 코드가 아니라 depth만 만드는 껍데기다.

// 여백 10칸 → tier1 구슬
export function shallow(): void {
  a(() => {
    b(() => {
      c(() => {
        d(() => {
          run();
        });
      });
    });
  });
}


// 여백 16칸 → tier2 클래식 파동권
export function medium(): void {
  a(() => {
    b(() => {
      c(() => {
        d(() => {
          e(() => {
            f(() => {
              g(() => {
                run();
              });
            });
          });
        });
      });
    });
  });
}


// 여백 22칸 → tier3 플레어
export function deep(): void {
  a(() => {
    b(() => {
      c(() => {
        d(() => {
          e(() => {
            f(() => {
              g(() => {
                h(() => {
                  i(() => {
                    j(() => {
                      run();
                    });
                  });
                });
              });
            });
          });
        });
      });
    });
  });
}
